# lib/Report.ps1
# Writes a markdown evaluation report.

function Write-EvalReport {
    param(
        [string]$Path,
        [object[]]$Results,
        [hashtable]$Config,
        [string]$SkillRoot,
        [datetime]$StartedAt
    )
    $endedAt = Get-Date
    $duration = $endedAt - $StartedAt

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("# B4XDaisyUIKit-Skills Evaluation Report")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("- **Suite path:** ``$SkillRoot``")
    [void]$sb.AppendLine("- **Started:** $StartedAt")
    [void]$sb.AppendLine("- **Ended:** $endedAt")
    [void]$sb.AppendLine("- **Duration:** $([int]$duration.TotalSeconds)s")
    [void]$sb.AppendLine("- **Layers run:** $($Results.Count)")
    [void]$sb.AppendLine("")

    # Summary table
    [void]$sb.AppendLine("## Summary")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("| Layer | Status | Score | Detail |")
    [void]$sb.AppendLine("| ----- | ------ | ----- | ------ |")
    foreach ($r in $Results) {
        $score = if ($null -ne $r.Score) { ('{0:P1}' -f $r.Score) } else { '-' }
        [void]$sb.AppendLine("| $($r.Layer) | $($r.Status) | $score | $($r.Detail) |")
    }
    [void]$sb.AppendLine("")

    # Per-layer details
    [void]$sb.AppendLine("## Per-Layer Results")
    [void]$sb.AppendLine("")
    foreach ($r in $Results) {
        [void]$sb.AppendLine("### $($r.Layer) - $($r.Status)")
        [void]$sb.AppendLine("")
        if ($r.Score -ne $null) {
            [void]$sb.AppendLine("- **Score:** $([math]::Round($r.Score * 100, 1))%")
        }
        [void]$sb.AppendLine("- **Detail:** $($r.Detail)")
        if ($r.Checks -and $r.Checks.Count -gt 0) {
            [void]$sb.AppendLine("")
            [void]$sb.AppendLine("**Checks:**")
            [void]$sb.AppendLine("")
            foreach ($c in $r.Checks) {
                $glyph = switch ($c.Status) {
                    'pass'  { 'PASS' }
                    'warn'  { 'WARN' }
                    'fail'  { 'FAIL' }
                    default { '???'  }
                }
                [void]$sb.AppendLine("- [$glyph] $($c.Name) - $($c.Detail)")
            }
        }
        [void]$sb.AppendLine("")
    }

    # Footer
    [void]$sb.AppendLine("---")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("_Generated by `b4xdaisyuikit-skills/eval` harness at $endedAt._")

    Set-Content -Path $Path -Value $sb.ToString() -Encoding UTF8
}